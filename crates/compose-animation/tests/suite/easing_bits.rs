fn check(easing: Easing, expected: &[(u32, u32)]) {
    let mut wrong = Vec::new();
    for &(fraction, eased) in expected {
        let fraction = f32::from_bits(fraction);
        let actual = easing.transform(fraction);
        if actual.to_bits() != eased {
            wrong.push((fraction, actual, f32::from_bits(eased)));
        }
    }
    assert!(wrong.is_empty(), "{} of {} differ: {wrong:?}", wrong.len(), expected.len());
}
