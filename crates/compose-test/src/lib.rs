/// The default test root: a phone-sized window at density 1.
pub const DEFAULT_SIZE: IntSize = IntSize::new(400, 800);

thread_local! {
    /// What [`use_optimizations`] set for the rules made on this thread.
    static OPTIMIZATIONS: std::cell::Cell<Option<Optimizations>> = const { std::cell::Cell::new(None) };
}

/// The rules made on this thread from now on give their hosts `optimizations`
/// (`UiHost::set_optimizations`) before composing. Without it a rule's host has the defaults,
/// the recommended set, so tests exercise what ships (D610): `Optimizations::NONE` for a test
/// of Compose's own behaviour (parity), another set for a test of flags beyond it (D520). Each
/// test runs on a thread of its own, so it holds for the test that calls it.
pub fn use_optimizations(optimizations: Optimizations) {
    OPTIMIZATIONS.with(|cell| cell.set(Some(optimizations)));
}

/// The optimizations [`use_optimizations`] set for this thread's rules, if any.
fn thread_optimizations() -> Option<Optimizations> {
    OPTIMIZATIONS.with(std::cell::Cell::get)
}

/// A headless host of the default size, for [`ComposeTestRule::empty`].
pub fn default_host() -> UiHost {
    UiHost::headless(DEFAULT_SIZE.width, DEFAULT_SIZE.height)
}
